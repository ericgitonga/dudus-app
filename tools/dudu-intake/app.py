from pathlib import Path

import fitz
import streamlit as st
from PIL import Image, ImageOps

REPO_ROOT = Path(__file__).resolve().parents[2]
CARD_INDEX_PATH = REPO_ROOT / "src" / "data" / "card_index.json"
PHOTOS_DIR = REPO_ROOT / "public" / "photos"
DUDUS_ROOT = REPO_ROOT.parent / "Dudus"

GITHUB_REPO = "ericgitonga/dudus-app"
CI_POLL_INTERVAL_SECONDS = 8
CI_POLL_TIMEOUT_SECONDS = 600

CARD_KEY_ORDER = [
    "id",
    "common_name",
    "scientific_name",
    "family",
    "order",
    "taxon_rank",
    "sourcing",
    "sections",
    "source_report_ref",
    "photo_ref",
    "reviewed_by",
    "reviewed_at",
]

# These three have no edit UI yet (only photos do) — left as clearly-a-placeholder values for a
# human to fill in by hand later, not guessed at.
DEFAULT_TAXON_RANK = "species"
DEFAULT_SOURCING = ""

ORDER_UNKNOWN_LABEL = "Unknown (fix later)"
ORDER_OTHER_LABEL = "Other (type manually)"

TARGET_RATIO = 3 / 2
RATIO_TOLERANCE = 0.02

# Font sizes below come from md_to_pdf_rl.py's H1/H2 ParagraphStyles (20pt / 15pt, both bold) —
# the same converter that produced every existing lay report. A generous floor (18/12) tolerates
# minor font-substitution drift without needing exact pt matches.
TITLE_MIN_SIZE = 18
HEADING_MIN_SIZE = 12


def load_cards():
    with open(CARD_INDEX_PATH) as f:
        return json.load(f)


def serialize_cards(cards):
    return (json.dumps(cards, indent=2, ensure_ascii=False) + "\n").encode()


def save_cards(cards):
    with open(CARD_INDEX_PATH, "wb") as f:
        f.write(serialize_cards(cards))


def slugify(text):
    slug = re.sub(r"[^a-z0-9]+", "-", text.strip().lower())
    return slug.strip("-")


def parse_lay_report(pdf_bytes):
    """
    Extract (title, sections, error) from a lay-report PDF generated by md_to_pdf_rl.py. The
    title is the report's own H1 (the common name, as authored); every subsequent bold heading
    starts a new section, with regular-weight text collected as that section's body until the
    next heading. Returns error=None on success, or a human-readable reason parsing failed.
    """
    doc = fitz.open(stream=pdf_bytes, filetype="pdf")
    lines = []
    for page in doc:
        for block in page.get_text("dict")["blocks"]:
            for line in block.get("lines", []):
                spans = line["spans"]
                text = "".join(s["text"] for s in spans).strip()
                if not text:
                    continue
                size = max(s["size"] for s in spans)
                bold = any("Bold" in s["font"] for s in spans)
                lines.append((text, size, bold))

    title = None
    sections = []
    current = None
    for text, size, bold in lines:
        if title is None and bold and size >= TITLE_MIN_SIZE:
            title = text
            continue
        if bold and size >= HEADING_MIN_SIZE:
            current = {"heading": text, "body": []}
            sections.append(current)
            continue
        if current is not None:
            current["body"].append(text)

    if title is None:
        return None, [], "Couldn't find a title (no large bold heading) — is this the right PDF?"
    if not sections:
        return title, [], "Found a title but no section headings — is this the lay report, not the technical one?"

    # Some reports phrase the title as a sentence ("The White-Ringed Atlas Moth") rather than a
    # bare name — no existing common_name in card_index.json starts with an article, so this is
    # always noise to drop, never a legitimate part of the name.
    title = re.sub(r"^(the|an?)\s+", "", title, flags=re.IGNORECASE)

    return title, [{"heading": s["heading"], "body": " ".join(s["body"])} for s in sections], None


def find_technical_pdf_path(common_name, lay_filename):
    """Look for the sibling technical PDF (same name minus "-la") in Dudus/<common_name>/, per
    the naming convention every existing report follows. None if this machine has no Dudus/
    checkout or no match is found."""
    technical_filename = lay_filename.replace("-la.pdf", ".pdf")
    if technical_filename == lay_filename:
        return None
    candidate = DUDUS_ROOT / common_name / technical_filename
    return candidate if candidate.exists() else None


def find_technical_ref(common_name, lay_filename):
    """String form of find_technical_pdf_path for source_report_ref — empty string (not None,
    the schema doesn't allow null here) if there's no match."""
    path = find_technical_pdf_path(common_name, lay_filename)
    return f"{common_name}/{path.name}" if path else ""


def guess_order_from_technical(technical_path):
    """
    Every technical report states the taxonomic order in prose during its "Taxonomy and
    Classification" section (e.g. "Order Hemiptera", "belong to Order Araneae") — consistent
    enough across the corpus to regex for, though it's a heuristic over free text, not a
    structured field. Returns the most common match, or None if the file is missing or the
    pattern isn't found (caller falls back to manual entry either way).
    """
    if not technical_path:
        return None
    doc = fitz.open(str(technical_path))
    text = "\n".join(page.get_text() for page in doc)
    matches = re.findall(r"\bOrder\s+([A-Z][a-zA-Z]+)\b", text)
    if not matches:
        return None
    return Counter(matches).most_common(1)[0][0]


def order_card(card):
    return {k: card.get(k) for k in CARD_KEY_ORDER}


def process_photo(uploaded_file):
    """
    Strip EXIF/GPS metadata and bake in orientation, mirroring stripPhotoMetadata.ts (#10) so
    admin-uploaded photos get the same treatment as in-app captures. Then apply the pad-to-3:2
    convention from SKILL.md: only pads (never crops) since "crop tight to the dudu" is a manual
    judgment call the tool can't make. Returns (image, warning | None).
    """
    img = Image.open(uploaded_file)
    img = ImageOps.exif_transpose(img)
    img = img.convert("RGB")

    w, h = img.size
    ratio = w / h
    warning = None

    if ratio < TARGET_RATIO - RATIO_TOLERANCE:
        target_w = round(h * TARGET_RATIO)
        padded = Image.new("RGB", (target_w, h), "white")
        padded.paste(img, ((target_w - w) // 2, 0))
        img = padded
    elif ratio > TARGET_RATIO + RATIO_TOLERANCE:
        warning = (
            f"This photo is wider than 3:2 ({w}x{h}). The tool only pads narrow photos — "
            "it won't crop into the subject automatically. Crop it tighter yourself first "
            "(see SKILL.md's photo convention), or upload as-is and expect some edge crop "
            "on the site's 3:2/4:3 views."
        )

    return img, warning


def save_photo(img, card_id, ext):
    PHOTOS_DIR.mkdir(parents=True, exist_ok=True)
    filename = f"{card_id}.{ext}"
    fmt = "PNG" if ext == "png" else "JPEG"
    img.save(PHOTOS_DIR / filename, fmt)
    return f"/photos/{filename}"


def delete_photo(photo_ref):
    if not photo_ref:
        return
    path = REPO_ROOT / "public" / photo_ref.lstrip("/")
    if path.exists():
        path.unlink()


def run_cmd(args, cwd, check=True):
    result = subprocess.run(args, cwd=str(cwd), capture_output=True, text=True)
    if check and result.returncode != 0:
        raise RuntimeError(
            f"`{' '.join(args)}` failed (exit {result.returncode}):\n{result.stdout}\n{result.stderr}"
        )
    return result.stdout.strip()


def publish_content_change(files, commit_message, pr_title, pr_body, log):
    """
    Drive the existing branch -> PR -> e2e -> squash-merge pipeline for a content-only change,
    so using this tool actually publishes to the live site (#34) without VERSION/CHANGELOG/tag
    ceremony or a per-change issue — same reasoning as career-transition's per-client CV/plan
    exemption from issue-first (this is content, not a codebase change).

    `files` maps repo-relative paths to new bytes, or None to delete that path. Runs entirely in
    a throwaway git worktree on its own branch — never checks out anything in REPO_ROOT itself,
    so a concurrently-running instance of this same tool (or an admin's own unrelated local
    edits) in the live working directory is never disturbed.

    Returns (published: bool, pr_url: str | None, detail: str).
    """
    branch = f"intake/{uuid.uuid4().hex[:10]}"
    worktree_dir = Path(tempfile.mkdtemp(prefix="dudu-intake-publish-"))
    pr_url = None
    try:
        log("Fetching latest `main`…")
        run_cmd(["git", "fetch", "origin", "main"], REPO_ROOT)

        log(f"Preparing an isolated worktree on `{branch}`…")
        run_cmd(["git", "worktree", "add", "-b", branch, str(worktree_dir), "origin/main"], REPO_ROOT)

        for rel_path, content in files.items():
            dest = worktree_dir / rel_path
            if content is None:
                if dest.exists():
                    dest.unlink()
            else:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(content)
            run_cmd(["git", "add", "--", rel_path], worktree_dir)

        run_cmd(["git", "commit", "-m", commit_message], worktree_dir)

        log("Pushing…")
        run_cmd(["git", "push", "-u", "origin", branch], worktree_dir)

        log("Opening PR…")
        pr_url = run_cmd(
            [
                "gh", "pr", "create", "--repo", GITHUB_REPO,
                "--title", pr_title, "--body", pr_body, "--head", branch,
            ],
            worktree_dir,
        )
        pr_number = pr_url.rstrip("/").split("/")[-1]

        log(f"PR {pr_url} opened — waiting for checks…")
        deadline = time.time() + CI_POLL_TIMEOUT_SECONDS
        checks = []
        while time.time() < deadline:
            checks_raw = run_cmd(
                ["gh", "pr", "checks", pr_number, "--repo", GITHUB_REPO, "--json", "name,bucket"],
                worktree_dir,
                check=False,
            )
            checks = json.loads(checks_raw) if checks_raw else []
            if checks and all(c["bucket"] != "pending" for c in checks):
                break
            time.sleep(CI_POLL_INTERVAL_SECONDS)
        else:
            return False, pr_url, "Timed out waiting for checks — PR left open for manual review."

        failed = [c["name"] for c in checks if c["bucket"] not in ("pass", "skipping")]
        if failed:
            return False, pr_url, f"Checks failed ({', '.join(failed)}) — PR left open, not merged."

        log("Checks green — merging…")
        run_cmd(
            ["gh", "pr", "merge", pr_number, "--repo", GITHUB_REPO, "--squash", "--delete-branch"],
            worktree_dir,
        )
        return True, pr_url, "Published to the live site."
    finally:
        log("Cleaning up the temporary worktree…")
        run_cmd(["git", "worktree", "remove", "--force", str(worktree_dir)], REPO_ROOT, check=False)
        shutil.rmtree(worktree_dir, ignore_errors=True)
        # Best-effort: if this succeeded, the live working directory's own copy of these files
        # already matches what was just merged (we published its exact current bytes), so this
        # is just bookkeeping to mark it clean — never something to block or error the UI on. Only
        # when REPO_ROOT is actually on `main` — if it's sitting on some other branch (e.g. a dev
        # session working on the tool itself), silently pulling there would be exactly the kind
        # of surprise branch-state change this worktree approach exists to avoid.
        current_branch = run_cmd(["git", "branch", "--show-current"], REPO_ROOT, check=False)
        if current_branch == "main":
            run_cmd(["git", "pull", "--ff-only"], REPO_ROOT, check=False)


def revert_local_files(paths):
    """
    Best-effort: put each path back to its last-committed (HEAD) state — restores a
    deleted/modified tracked file, removes an untracked new one. Used whenever a publish fails,
    so the local working tree never drifts ahead of `main` with content nothing else knows
    about — the next action (single or batch) always starts from a clean, HEAD-matching base.
    """
    for rel_path in paths:
        full = REPO_ROOT / rel_path
        tracked = subprocess.run(
            ["git", "ls-files", "--error-unmatch", rel_path],
            cwd=REPO_ROOT, capture_output=True, text=True,
        ).returncode == 0
        if tracked:
            run_cmd(["git", "checkout", "HEAD", "--", rel_path], REPO_ROOT, check=False)
        elif full.exists():
            full.unlink()


def do_publish(files, commit_message, pr_title, pr_body):
    with st.status("Publishing to the live site…", expanded=True) as status:
        try:
            published, pr_url, detail = publish_content_change(
                files, commit_message, pr_title, pr_body, status.write
            )
        except Exception as e:
            status.update(label="Publish failed", state="error")
            st.error(f"Publish failed: {e}")
            revert_local_files(files.keys())
            return False
        status.update(
            label="Published" if published else "Not published",
            state="complete" if published else "error",
        )
        (st.success if published else st.warning)(f"{detail}\n\n{pr_url}" if pr_url else detail)
        if not published:
            revert_local_files(files.keys())
        return published


def order_picker(key_prefix, known_orders, detected_order):
    """
    Selectbox over orders already in use, plus "Unknown" and a manual write-in — because a
    genuinely new order (like Phasmatodea for the first stick insect card) won't be in
    `known_orders` yet, and a dropdown alone can't offer something not already in the data.
    Pre-selects `detected_order` (from guess_order_from_technical) when there is one: exactly if
    it's already a known order, or pre-fills the write-in field with it otherwise so the admin
    only has to confirm, not retype.
    """
    options = known_orders + [ORDER_UNKNOWN_LABEL, ORDER_OTHER_LABEL]
    if detected_order and detected_order in known_orders:
        default_index = known_orders.index(detected_order)
    elif detected_order:
        default_index = len(known_orders) + 1  # ORDER_OTHER_LABEL
    else:
        default_index = len(known_orders)  # ORDER_UNKNOWN_LABEL

    # Keyed on detected_order too, not just key_prefix: st.selectbox only honours a fresh
    # `index=` the first time a given key renders — a new PDF upload landing on the *same* key
    # (e.g. detected_order going from None to "Phasmatodea") would otherwise keep showing
    # whatever the first render defaulted to, same class of bug fixed earlier for text_input.
    choice = st.selectbox(
        "Order", options, index=default_index, key=f"{key_prefix}_order_select_{detected_order}"
    )
    if detected_order and choice == ORDER_OTHER_LABEL:
        st.caption(f"Detected from the technical report: `{detected_order}`")
    if choice == ORDER_OTHER_LABEL:
        manual = st.text_input(
            "Order (manual entry)",
            value=detected_order or "",
            key=f"{key_prefix}_order_manual_{detected_order}",
        )
        return manual.strip() or None
    if choice == ORDER_UNKNOWN_LABEL:
        return None
    return choice



                if parse_err:
                    st.error(parse_err)
                    batch_rows.append({"error": parse_err})
                    continue

                card_id = slugify(title)
                dup_err = None
                if any(c["id"] == card_id for c in batch_cards_now):
                    dup_err = f"id '{card_id}' already exists on the live site."
